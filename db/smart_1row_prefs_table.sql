-- Smart 1-Row View plug-in: per-user layout preferences (Allow User Configuration).
-- Safe to run again: existing objects are left alone.
declare
    procedure ddl ( p_sql in varchar2 ) is
    begin
        execute immediate p_sql;
    exception
        when others then
            -- -955 name in use, -2260/-2261 key exists, -1408 column list indexed
            if sqlcode not in (-955, -2260, -2261, -1408) then
                raise;
            end if;
    end ddl;
begin
    ddl(q'[
        create table smart_1row_prefs (
            pref_id        number generated by default on null as identity not null,
            app_id         number         not null,
            page_id        number         not null,
            region_key     varchar2(255)  not null,
            username       varchar2(255)  not null,
            hidden_columns varchar2(4000),
            column_order   varchar2(4000),
            created_on     timestamp default systimestamp not null,
            updated_on     timestamp default systimestamp not null,
            constraint smart_1row_prefs_pk primary key (pref_id),
            constraint smart_1row_prefs_uk unique (app_id, page_id, region_key, username)
        )]');
    ddl(q'[create index smart_1row_prefs_ix1 on smart_1row_prefs (username, app_id)]');
end;
/
